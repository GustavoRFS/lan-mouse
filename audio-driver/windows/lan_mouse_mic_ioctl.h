#pragma once

#include <ntddk.h>

#define LAMOUSE_MIC_DEVICE_TYPE FILE_DEVICE_UNKNOWN
#define IOCTL_LAN_MOUSE_MIC_WRITE \
    CTL_CODE(LAMOUSE_MIC_DEVICE_TYPE, 0x800, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_LAN_MOUSE_MIC_FLUSH \
    CTL_CODE(LAMOUSE_MIC_DEVICE_TYPE, 0x801, METHOD_BUFFERED, FILE_ANY_ACCESS)

#define LAMOUSE_MIC_SAMPLE_RATE 48000
#define LAMOUSE_MIC_CHANNELS 1
#define LAMOUSE_MIC_SAMPLES_PER_BLOCK 960
#define LAMOUSE_MIC_BYTES_PER_BLOCK 1920

/* IOCTL_LAN_MOUSE_MIC_WRITE input: exactly 960 signed 16-bit little-endian samples. */
typedef struct _LAMOUSE_MIC_PCM_BLOCK {
    SHORT Samples[LAMOUSE_MIC_SAMPLES_PER_BLOCK];
} LAMOUSE_MIC_PCM_BLOCK, *PLAMOUSE_MIC_PCM_BLOCK;
